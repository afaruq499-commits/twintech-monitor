import { PrismaClient } from "@prisma/client";
import {
  buildStandardPanelLayoutFromComponents,
  serializeDualPanelLayoutPayload,
} from "../src/lib/panel-layout-template";

const prisma = new PrismaClient({
  datasources: {
    db: {
      url: process.env.DIRECT_URL || process.env.DATABASE_URL,
    },
  },
});

async function main() {
  console.log("Menghubungkan ke Supabase...");

  const jig = await prisma.project.findFirst({
    where: { kode: "26 RKI 1012" },
    include: { components: true },
  });

  if (!jig) {
    console.error("Proyek 26 RKI 1012 tidak ditemukan di database!");
    return;
  }

  console.log(`Ditemukan proyek: ${jig.nama} (${jig.components.length} komponen)`);

  // 1. Generate Panel Layout lengkap
  const autoLayout = buildStandardPanelLayoutFromComponents(jig.components);
  const panelLayoutPayload = serializeDualPanelLayoutPayload({
    ...autoLayout,
    autoGenerated: true,
    templateCode: "FR-EG-EP-006",
    lastSaved: new Date().toISOString(),
  });

  // 2. Flowchart alur sekuens mesin
  const flowchartPayload = JSON.stringify({
    schemaVersion: 2,
    projectId: jig.id,
    primaryImageUrl: "/uploads/flowcharts/1793728067242_1_process_machine_running_v2.png",
    imageUrls: [
      "/uploads/flowcharts/1793728067242_1_process_machine_running_v2.png",
      "/uploads/flowcharts/1793728067248_2_process_safety_relay_v2.png",
    ],
    updatedAt: new Date().toISOString(),
  });

  // 3. Alamat I/O PLC
  const plcAddresses = [
    { address: "X0", type: "DI", symbol: "PB_START", description: "Tombol Start Siklus Otomatis" },
    { address: "X1", type: "DI", symbol: "PB_STOP", description: "Tombol Stop Siklus" },
    { address: "X2", type: "DI", symbol: "EMERGENCY_STOP", description: "Emergency Stop Panel Operator" },
    { address: "X3", type: "DI", symbol: "KEY_SW_AUTO", description: "Selector Switch Auto / Manual" },
    { address: "X4", type: "DI", symbol: "SAFETY_CURTAIN_OK", description: "Safety Light Curtain Area Protection" },
    { address: "X5", type: "DI", symbol: "PART_IN_POS", description: "Sensor Keberadaan Part Jig (Keyence LR-Z)" },
    { address: "X6", type: "DI", symbol: "CLAMP_CYL_FWD", description: "Reed Switch Silinder Clamp Maju" },
    { address: "X7", type: "DI", symbol: "CLAMP_CYL_REV", description: "Reed Switch Silinder Clamp Mundur" },
    { address: "Y0", type: "DO", symbol: "SOL_CLAMP_FWD", description: "Solenoid Valve Silinder Clamp Maju" },
    { address: "Y1", type: "DO", symbol: "SOL_CLAMP_REV", description: "Solenoid Valve Silinder Clamp Mundur" },
    { address: "Y2", type: "DO", symbol: "PILOT_LAMP_RUN", description: "Lampu Indikator Running Hijau" },
    { address: "Y3", type: "DO", symbol: "PILOT_LAMP_ALARM", description: "Lampu Indikator Alarm Merah" },
    { address: "Y4", type: "DO", symbol: "BUZZER_ALARM", description: "Buzzer Alarm Siklus NG / Pintu Terbuka" },
  ];

  // 4. Checklist 8 Berkas
  const fileChecklist = {
    komponen_pr: { checked: true, updatedAt: new Date().toISOString() },
    schedule_pengerjaan: { checked: true, updatedAt: new Date().toISOString() },
    alamat_io: { checked: true, updatedAt: new Date().toISOString() },
    layout_panel_hmi: { checked: true, updatedAt: new Date().toISOString() },
    layout_panel_utama: { checked: true, updatedAt: new Date().toISOString() },
    flowchart: { checked: true, updatedAt: new Date().toISOString() },
    diagram_wiring: { checked: false },
    pemprograman: { checked: false },
  };

  await prisma.project.update({
    where: { id: jig.id },
    data: {
      gambarUrl: "/uploads/project-images/1793379990339_Screenshot_2026-10-31_000619.png",
      panelLayoutJson: panelLayoutPayload,
      flowSequenceJson: flowchartPayload,
      plcAddressesJson: JSON.stringify(plcAddresses),
      fileChecklistJson: JSON.stringify(fileChecklist),
      wiringDiagramPdfUrl: "/uploads/flowcharts/1793728992030_1_26-RKI-1012.jpg",
      wiringDiagramPdfName: "Wiring Diagram 26-RKI-1012.dwg",
    },
  });

  console.log("Berhasil memperbarui data Proyek 26 RKI 1012 di Supabase!");

  // Proyek 2 juga disinkronkan layoutnya jika perlu
  const mgs = await prisma.project.findFirst({
    where: { kode: "26 MGS 0804" },
    include: { components: true },
  });
  if (mgs) {
    const mgsChecklist = {
      komponen_pr: { checked: false },
      schedule_pengerjaan: { checked: true, updatedAt: new Date().toISOString() },
      alamat_io: { checked: false },
      layout_panel_hmi: { checked: false },
      layout_panel_utama: { checked: false },
      flowchart: { checked: false },
      diagram_wiring: { checked: false },
      pemprograman: { checked: false },
    };
    await prisma.project.update({
      where: { id: mgs.id },
      data: {
        gambarUrl: "/uploads/project-images/1794147888656_WhatsApp_Image_2026-11-06_at_11_03_39.jpeg",
        fileChecklistJson: JSON.stringify(mgsChecklist),
      },
    });
    console.log("Berhasil memperbarui data Proyek 26 MGS 0804 di Supabase!");
  }
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
