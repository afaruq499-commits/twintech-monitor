/**
 * Mengubah daftar ID terpilih; bila multi=true (Ctrl/Cmd+Klik) melakukan toggle item.
 */
export function toggleSelectionId(
  selectedIds: string[],
  targetId: string,
  multi: boolean
): string[] {
  if (!multi) {
    return [targetId];
  }
  return selectedIds.includes(targetId)
    ? selectedIds.filter((id) => id !== targetId)
    : [...selectedIds, targetId];
}

/**
 * Menggeser sekumpulan item sekaligus sambil menjaga jarak relatif antar item dalam batas plat.
 */
export function moveSelectedPanelItems(
  items: PanelLayoutItem[],
  dragIds: string[],
  initialPositions: Record<string, { xMm: number; yMm: number }>,
  deltaX: number,
  deltaY: number,
  enclosure: { widthMm: number; heightMm: number }
): PanelLayoutItem[] {
  if (dragIds.length === 0) return items;

  const dragSet = new Set(dragIds);
  let minAllowedDx = -Infinity;
  let maxAllowedDx = Infinity;
  let minAllowedDy = -Infinity;
  let maxAllowedDy = Infinity;

  const maxX = Math.max(5, enclosure.widthMm - 20);
  const maxY = Math.max(5, enclosure.heightMm - 20);

  for (const id of dragIds) {
    const pos = initialPositions[id];
    if (!pos) continue;
    minAllowedDx = Math.max(minAllowedDx, 5 - pos.xMm);
    maxAllowedDx = Math.min(maxAllowedDx, maxX - pos.xMm);
    minAllowedDy = Math.max(minAllowedDy, 5 - pos.yMm);
    maxAllowedDy = Math.min(maxAllowedDy, maxY - pos.yMm);
  }

  const clampedDx =
    minAllowedDx <= maxAllowedDx
      ? Math.max(minAllowedDx, Math.min(maxAllowedDx, Math.round(deltaX)))
      : Math.round(deltaX);
  const clampedDy =
    minAllowedDy <= maxAllowedDy
      ? Math.max(minAllowedDy, Math.min(maxAllowedDy, Math.round(deltaY)))
      : Math.round(deltaY);

  return items.map((it) => {
    if (!dragSet.has(it.id)) return it;
    const init = initialPositions[it.id];
    if (!init) return it;
    return {
      ...it,
      xMm: init.xMm + clampedDx,
      yMm: init.yMm + clampedDy,
    };
  });
}

export type PanelAlignmentMode =
  | "LEFT"
  | "CENTER_X"
  | "RIGHT"
  | "TOP"
  | "CENTER_Y"
  | "BOTTOM";

/**
 * Menyejajarkan beberapa item terpilih relatif terhadap bounding box grup mereka.
 */
export function alignSelectedPanelItems(
  items: PanelLayoutItem[],
  selectedIds: string[],
  alignment: PanelAlignmentMode,
  enclosure: { widthMm: number; heightMm: number }
): PanelLayoutItem[] {
  const selectedSet = new Set(selectedIds);
  const targets = items.filter((it) => selectedSet.has(it.id));
  if (targets.length < 2) return items;

  const minX = Math.min(...targets.map((t) => t.xMm));
  const maxRight = Math.max(...targets.map((t) => t.xMm + t.widthMm));
  const centerX = (minX + maxRight) / 2;

  const minY = Math.min(...targets.map((t) => t.yMm));
  const maxBottom = Math.max(...targets.map((t) => t.yMm + t.heightMm));
  const centerY = (minY + maxBottom) / 2;

  const clampX = (x: number, w: number) =>
    Math.max(5, Math.min(Math.max(5, enclosure.widthMm - w - 5), Math.round(x)));
  const clampY = (y: number, h: number) =>
    Math.max(5, Math.min(Math.max(5, enclosure.heightMm - h - 5), Math.round(y)));

  return items.map((it) => {
    if (!selectedSet.has(it.id)) return it;
    switch (alignment) {
      case "LEFT":
        return { ...it, xMm: clampX(minX, it.widthMm) };
      case "CENTER_X":
        return { ...it, xMm: clampX(centerX - it.widthMm / 2, it.widthMm) };
      case "RIGHT":
        return { ...it, xMm: clampX(maxRight - it.widthMm, it.widthMm) };
      case "TOP":
        return { ...it, yMm: clampY(minY, it.heightMm) };
      case "CENTER_Y":
        return { ...it, yMm: clampY(centerY - it.heightMm / 2, it.heightMm) };
      case "BOTTOM":
        return { ...it, yMm: clampY(maxBottom - it.heightMm, it.heightMm) };
    }
  });
}
