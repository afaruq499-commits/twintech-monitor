/**
 * Deteksi apakah komponen PR adalah sensor/komponen lapangan (bukan isi panel kontrol).
 */
export function isSensorOrFieldComponent(
  partType: string,
  partName: string,
  kelompok: string
): boolean {
  const t = `${partType} ${partName} ${kelompok}`.toUpperCase();

  // Pastikan Stopper DIN rail / End Clamp / Terminal / Exhaust Fan panel tidak salah terfilter sebagai sensor/pneumatik
  const isDinStopper =
    t.includes("HDV-1") ||
    t.includes("END CLAMP") ||
    t.includes("STOPPER DIN") ||
    t.includes("STOPPER DINRAIL") ||
    t.includes("STOPPER TERMINAL") ||
    (t.includes("STOPPER") && (t.includes("TERMINAL") || t.includes("DIN") || t.includes("TOGI") || t.includes("HYBT") || t.includes("TBR")));

  if (
    t.includes("SENSOR") ||
    t.includes("PROXIMITY") ||
    t.includes("PROX") ||
    t.includes("PHOTO") ||
    t.includes("FOTOSEL") ||
    t.includes("FIBER") ||
    t.includes("ULTRASONIC") ||
    t.includes("ENCODER") ||
    t.includes("LIMIT SWITCH") ||
    t.includes("LIMIT SW") ||
    (!isDinStopper && t.includes("END STOP")) ||
    t.includes("REED SWITCH") ||
    t.includes("INDUCTIVE") ||
    t.includes("CAPACITIVE") ||
    t.includes("DIFFUSE") ||
    t.includes("RETRO") ||
    t.includes("THROUGH BEAM") ||
    t.includes("LASER") ||
    t.includes("THERMOCOUPLE") ||
    t.includes("RTD") ||
    t.includes("PRESSURE SENSOR") ||
    t.includes("LOADCELL") ||
    t.includes("LOAD CELL")
  ) {
    return true;
  }

  // Aktuator lapangan
  if (
    t.includes("SILINDER") ||
    t.includes("CYLINDER") ||
    t.includes("PNEUMATIC") ||
    t.includes("PNEUMATIK") ||
    t.includes("ACTUATOR") ||
    t.includes("AKTUATOR") ||
    t.includes("SOLENOID VALVE") ||
    t.includes("VALVE") ||
    t.includes("SERVO MOTOR") ||
    t.includes("SERVO MOT") ||
    t.includes("STEPPER") ||
    (t.includes("MOTOR") &&
      !t.includes("BREAKER") &&
      !t.includes("CONTACTOR") &&
      !t.includes("KONTAKTOR")) ||
    t.includes("SPINDLE") ||
    t.includes("VFD MOTOR") ||
    t.includes("GEAR BOX") ||
    t.includes("GEARBOX")
  ) {
    return true;
  }

  // Kabel roll / wire instalasi (kecuali cable duct, cable tray, cable gland, cable clamp, kabel ekstensi RJ45)
  if (
    (t.includes("KABEL") || t.includes("CABLE") || t.includes("WIRE")) &&
    !t.includes("DUCT") &&
    !t.includes("TRAY") &&
    !t.includes("GLAND") &&
    !t.includes("CLAMP") &&
    !t.includes("RJ45")
  ) {
    return true;
  }

  // Consumables instalasi
  if (
    t.includes("SKUN") ||
    t.includes("FERRULE") ||
    t.includes("CABLE TIE") ||
    t.includes("KABEL TIE") ||
    t.includes("SPIRAL WRAP") ||
    t.includes("HEAT SHRINK") ||
    t.includes("HEATSHRINK") ||
    t.includes("KABEL BAKAR") ||
    (t.includes("ISOLASI") && !t.includes("TRAFO") && !t.includes("TRANSFORMER")) ||
    t.includes("MARKING TUBE") ||
    t.includes("TUBE MARKER")
  ) {
    return true;
  }

  // Mekanik & hardware struktural mesin
  if (
    t.includes("BAUT") ||
    t.includes("MUER") ||
    (/\bRING\b/.test(t) && !t.includes("MEASURING")) ||
    t.includes("BRACKET") ||
    (t.includes("MOUNTING PLATE") && !t.includes("PANEL")) ||
    t.includes("L BRACKET") ||
    t.includes("PROFIL ALUMINIUM") ||
    t.includes("LINER") ||
    t.includes("RUBBER") ||
    t.includes("GASKET") ||
    t.includes("SEAL") ||
    (t.includes("SPRING") && !t.includes("TERMINAL") && !t.includes("SWITCH") && !t.includes("BUTTON")) ||
    t.includes("BEARING") ||
    t.includes("CHAIN") ||
    t.includes("BELT") ||
    t.includes("PULLEY") ||
    t.includes("BUSHING") ||
    t.includes("COLLAR") ||
    t.includes("INSERT") ||
    t.includes("SPAREPART")
  ) {
    return true;
  }

  // Pneumatik & hidrolik (exhaust fan / filter panel dikecualikan agar tetap terbaca)
  const isPanelVentilation =
    t.includes("FAN") ||
    t.includes("12CM") ||
    t.includes("9CM") ||
    t.includes("PANEL") ||
    t.includes("FORT") ||
    t.includes("COOLING") ||
    t.includes("FINGER GUARD");

  if (
    t.includes("SELANG") ||
    t.includes("HOSE") ||
    t.includes("FITTING") ||
    t.includes("COUPLER") ||
    t.includes("FRL") ||
    t.includes("REGULATOR") ||
    t.includes("FILTER UDARA") ||
    t.includes("LUBRICATOR") ||
    t.includes("MUFFLER") ||
    (t.includes("EXHAUST") && !isPanelVentilation) ||
    t.includes("MANIFOLD") ||
    t.includes("FLOW CONTROL") ||
    t.includes("SPEED CONTROLLER")
  ) {
    return true;
  }

  // Komponen mesin / jig / fixture (kecuali Cable Clamp atau Spring Clamp Terminal)
  if (
    t.includes("JIG") ||
    t.includes("FIXTURE") ||
    t.includes("DIE") ||
    t.includes("MOLD") ||
    t.includes("TOOLING") ||
    t.includes("CHUCK") ||
    (t.includes("CLAMP") &&
      !isDinStopper &&
      !t.includes("KABEL") &&
      !t.includes("CABLE") &&
      !t.includes("TERMINAL")) ||
    t.includes("GRIPPER") ||
    (t.includes("FINGER") && !t.includes("GUARD")) ||
    t.includes("NOZZLE") ||
    /\bROLLER\b/.test(t) ||
    t.includes("SHAFT") ||
    t.includes("BALL SCREW") ||
    t.includes("LINEAR GUIDE") ||
    t.includes("SLIDE UNIT")
  ) {
    return true;
  }

  // Mekanikal struktural rangka mesin
  if (
    t.includes("FRAME") ||
    t.includes("PLAT BESI") ||
    t.includes("BESI SIKU") ||
    t.includes("HOLLOW") ||
    t.includes("PLAT BAJA") ||
    /\bUNP\b/.test(t) ||
    /\bINP\b/.test(t) ||
    t.includes("PIPA") ||
    t.includes("PIPE")
  ) {
    return true;
  }

  return false;
}

