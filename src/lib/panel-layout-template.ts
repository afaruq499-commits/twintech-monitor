    t.includes("MCB") ||
    t.includes("MCCB") ||
    t.includes("STOP KONTAK") ||
    t.includes("UTICON") ||
    t.includes("SN-016") ||
    t.includes("CR-2801") ||
    t.includes("RELAY") ||
    t.includes("POWER SUPPLY") ||
    t.includes("POWER SUPLAY") ||
    t.includes("SMPS") ||
    t.includes("S8VK") ||
    t.includes("SPB-") ||
    t.includes("PS5R") ||
    t.includes("NOISE FILTER") ||
    t.includes("RSEN") ||
    t.includes("RSAL");

  if (
    (!isInternalOpMountingPart &&
      (t.includes("OP PANEL") || t.includes("BOX OPERATOR") || t.includes("BOX PB"))) ||
    t.includes("DESK OP") ||
    t.includes("PENDANT") ||
    (!/\bHUB\b/.test(t) && t.includes("PORT") && (t.includes("RJ45") || t.includes("USB")))
  ) {
    return true;
  }

  return false;
