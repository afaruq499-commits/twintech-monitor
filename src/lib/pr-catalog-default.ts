export interface CatalogItemFields {
  kategori: string;
  nama: string;
  merek: string;
  tipeModel: string;
  spesifikasi?: string | null;
  estimasiHarga?: number | null;
  defaultUnit?: string | null;
}

/**
 * Mengonversi item katalog menjadi kolom standar Purchase Requisition (File 1):
 * - partType (Kolom B:C PART TYPE) = Merek + Tipe/Model
 * - partName (Kolom D:F PARTS NAME) = Nama / Jenis Komponen
 */
export function formatCatalogItemForPr(item: CatalogItemFields) {
  const brand = item.merek.trim();
  const model = item.tipeModel.trim();
  const skipBrand =
    !brand ||
    brand === "-" ||
    brand.toLowerCase() === "bebas" ||
    model.toLowerCase().includes(brand.toLowerCase());

  const partType = skipBrand ? model : `${brand} ${model}`;
  return {
    partType,
    partName: item.nama.trim(),
    unit: item.defaultUnit?.trim() || "pcs",
    hargaSatuan: item.estimasiHarga ?? null,
  };
}
